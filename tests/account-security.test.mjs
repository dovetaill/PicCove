async function request(path, body, status = 200) {
  const response = await context.request.fetch(`${origin}/api/v1${path}`, { method: body ? 'POST' : 'GET', data: body, headers: { Origin: origin } });
  assert.equal(response.status(), status, `${path}: ${await response.text()}`);
  return response.status() === 204 ? null : response.json();
}
function code(secret, offset = 0) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  const bits = [...secret].map(c => alphabet.indexOf(c).toString(2).padStart(5, '0')).join('');
  const key = Buffer.from(bits.match(/.{8}/g).map(v => parseInt(v, 2)));
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000) + offset));
  const hash = createHmac('sha1', key).update(counter).digest();
  return String((hash.readUInt32BE(hash[19] & 15) & 0x7fffffff) % 1000000).padStart(6, '0');
}
